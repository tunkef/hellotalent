-- ── admin_create_studio_module ──
CREATE OR REPLACE FUNCTION admin_create_studio_module(
  p_section text,
  p_module_type text,
  p_title text,
  p_slug text,
  p_summary text DEFAULT NULL,
  p_body_md text DEFAULT NULL,
  p_cover_image_url text DEFAULT NULL,
  p_cover_image_alt text DEFAULT NULL,
  p_duration_minutes int DEFAULT NULL,
  p_cta_label text DEFAULT NULL,
  p_cta_url text DEFAULT NULL,
  p_sort_order int DEFAULT 0
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_id bigint;
BEGIN
  IF NOT is_admin() THEN
    RAISE EXCEPTION 'Yetki hatasi: admin erisimi gereklidir.';
  END IF;

  INSERT INTO studio_modules (
    section, module_type, slug, title, summary, body_md,
    cover_image_url, cover_image_alt, duration_minutes,
    cta_label, cta_url, sort_order, created_by
  ) VALUES (
    p_section, p_module_type, p_slug, p_title, p_summary, p_body_md,
    p_cover_image_url, p_cover_image_alt, p_duration_minutes,
    p_cta_label, p_cta_url, p_sort_order, auth.uid()
  ) RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION admin_create_studio_module FROM PUBLIC;
GRANT EXECUTE ON FUNCTION admin_create_studio_module TO authenticated;


-- ── admin_update_studio_module ──
CREATE OR REPLACE FUNCTION admin_update_studio_module(
  p_id bigint,
  p_data jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT is_admin() THEN
    RAISE EXCEPTION 'Yetki hatasi: admin erisimi gereklidir.';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM studio_modules WHERE id = p_id) THEN
    RAISE EXCEPTION 'Modul bulunamadi.';
  END IF;

  UPDATE studio_modules SET
    section          = COALESCE(p_data->>'section', section),
    module_type      = COALESCE(p_data->>'module_type', module_type),
    title            = COALESCE(p_data->>'title', title),
    slug             = COALESCE(p_data->>'slug', slug),
    summary          = CASE WHEN p_data ? 'summary' THEN p_data->>'summary' ELSE summary END,
    body_md          = CASE WHEN p_data ? 'body_md' THEN p_data->>'body_md' ELSE body_md END,
    cover_image_url  = CASE WHEN p_data ? 'cover_image_url' THEN p_data->>'cover_image_url' ELSE cover_image_url END,
    cover_image_alt  = CASE WHEN p_data ? 'cover_image_alt' THEN p_data->>'cover_image_alt' ELSE cover_image_alt END,
    duration_minutes = CASE WHEN p_data ? 'duration_minutes' THEN (p_data->>'duration_minutes')::int ELSE duration_minutes END,
    cta_label        = CASE WHEN p_data ? 'cta_label' THEN p_data->>'cta_label' ELSE cta_label END,
    cta_url          = CASE WHEN p_data ? 'cta_url' THEN p_data->>'cta_url' ELSE cta_url END,
    sort_order       = CASE WHEN p_data ? 'sort_order' THEN (p_data->>'sort_order')::int ELSE sort_order END
  WHERE id = p_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION admin_update_studio_module(bigint, jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION admin_update_studio_module(bigint, jsonb) TO authenticated;


-- ── admin_publish_studio_module ──
CREATE OR REPLACE FUNCTION admin_publish_studio_module(p_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT is_admin() THEN
    RAISE EXCEPTION 'Yetki hatasi: admin erisimi gereklidir.';
  END IF;

  UPDATE studio_modules
    SET status = 'published', published_at = now()
    WHERE id = p_id AND status IN ('draft', 'archived');

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Modul bulunamadi veya zaten yayinda.';
  END IF;
END;
$$;

REVOKE EXECUTE ON FUNCTION admin_publish_studio_module(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION admin_publish_studio_module(bigint) TO authenticated;


