-- Studio Modules — admin-managed learning content for Performans + HelloTalent'ten Bilgiler
-- Date: 2026-03-26
-- Type: SCHEMA + RLS + RPC + TRIGGER
-- Purpose:
--   1. studio_modules table — admin-managed content
--   2. candidate_studio_progress table — candidate progress tracking
--   3. RLS policies for candidate read + admin CRUD
--   4. Admin RPCs for module management
--   5. updated_at trigger

-- ═══════════════════════════════════════════════
-- 1. STUDIO MODULES
-- ═══════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS studio_modules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section text NOT NULL,
  module_type text NOT NULL DEFAULT 'article',
  slug text UNIQUE NOT NULL,
  title text NOT NULL,
  summary text,
  body_md text,
  cover_image_url text,
  cover_image_alt text,
  duration_minutes int,
  cta_label text,
  cta_url text,
  sort_order int DEFAULT 0,
  status text NOT NULL DEFAULT 'draft',
  published_at timestamptz,
  created_by uuid,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

ALTER TABLE studio_modules ADD CONSTRAINT studio_modules_section_check
  CHECK (section IN ('performans', 'bilgiler'));

ALTER TABLE studio_modules ADD CONSTRAINT studio_modules_type_check
  CHECK (module_type IN ('article', 'video', 'carousel', 'lesson'));

ALTER TABLE studio_modules ADD CONSTRAINT studio_modules_status_check
  CHECK (status IN ('draft', 'published', 'archived'));

CREATE INDEX IF NOT EXISTS idx_studio_modules_section_status
  ON studio_modules (section, status, sort_order);

-- updated_at trigger
CREATE OR REPLACE FUNCTION update_studio_modules_updated_at()
RETURNS TRIGGER AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_studio_modules_updated_at ON studio_modules;
CREATE TRIGGER trg_studio_modules_updated_at
  BEFORE UPDATE ON studio_modules
  FOR EACH ROW EXECUTE FUNCTION update_studio_modules_updated_at();

-- RLS
ALTER TABLE studio_modules ENABLE ROW LEVEL SECURITY;

-- Candidates can read published modules
CREATE POLICY studio_modules_read_published ON studio_modules
  FOR SELECT TO authenticated
  USING (status = 'published');

-- Admin can read all modules
DROP POLICY IF EXISTS studio_modules_admin_all ON studio_modules;
CREATE POLICY studio_modules_admin_all ON studio_modules
  FOR ALL TO authenticated
  USING (is_admin())
  WITH CHECK (is_admin());


-- ═══════════════════════════════════════════════
-- 2. CANDIDATE STUDIO PROGRESS
-- ═══════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS candidate_studio_progress (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id bigint NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  module_id bigint NOT NULL REFERENCES studio_modules(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'not_started',
  progress_pct int DEFAULT 0,
  last_viewed_at timestamptz DEFAULT now(),
  completed_at timestamptz,
  created_at timestamptz DEFAULT now(),
  UNIQUE (candidate_id, module_id)
);

ALTER TABLE candidate_studio_progress ADD CONSTRAINT csp_status_check
  CHECK (status IN ('not_started', 'in_progress', 'completed'));

ALTER TABLE candidate_studio_progress ADD CONSTRAINT csp_progress_pct_check
  CHECK (progress_pct >= 0 AND progress_pct <= 100);

CREATE INDEX IF NOT EXISTS idx_csp_candidate ON candidate_studio_progress (candidate_id);

-- RLS
ALTER TABLE candidate_studio_progress ENABLE ROW LEVEL SECURITY;

-- Candidates see only own progress
CREATE POLICY csp_select_own ON candidate_studio_progress
  FOR SELECT TO authenticated
  USING (candidate_id = (SELECT id FROM candidates WHERE user_id = auth.uid()));

-- No direct INSERT/UPDATE — must go through RPC


