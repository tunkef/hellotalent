-- ── mark_studio_module_viewed ──
-- Upserts progress row: creates if not exists, updates last_viewed_at + status
CREATE OR REPLACE FUNCTION mark_studio_module_viewed(p_module_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_candidate_id bigint;
BEGIN
  SELECT id INTO v_candidate_id FROM candidates WHERE user_id = auth.uid();
  IF v_candidate_id IS NULL THEN
    RAISE EXCEPTION 'Aday profili bulunamadi.';
  END IF;

  -- Only track published modules
  IF NOT EXISTS (SELECT 1 FROM studio_modules WHERE id = p_module_id AND status = 'published') THEN
    RETURN; -- silently skip unpublished
  END IF;

  INSERT INTO candidate_studio_progress (candidate_id, module_id, status, last_viewed_at)
  VALUES (v_candidate_id, p_module_id, 'in_progress', now())
  ON CONFLICT (candidate_id, module_id)
  DO UPDATE SET last_viewed_at = now(),
    status = CASE WHEN candidate_studio_progress.status = 'not_started' THEN 'in_progress' ELSE candidate_studio_progress.status END;
END;
$$;

REVOKE EXECUTE ON FUNCTION mark_studio_module_viewed(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION mark_studio_module_viewed(bigint) TO authenticated;


-- ── complete_studio_module ──
CREATE OR REPLACE FUNCTION complete_studio_module(p_module_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_candidate_id bigint;
BEGIN
  SELECT id INTO v_candidate_id FROM candidates WHERE user_id = auth.uid();
  IF v_candidate_id IS NULL THEN
    RAISE EXCEPTION 'Aday profili bulunamadi.';
  END IF;

  INSERT INTO candidate_studio_progress (candidate_id, module_id, status, progress_pct, completed_at)
  VALUES (v_candidate_id, p_module_id, 'completed', 100, now())
  ON CONFLICT (candidate_id, module_id)
  DO UPDATE SET status = 'completed', progress_pct = 100, completed_at = now(), last_viewed_at = now();
END;
$$;

REVOKE EXECUTE ON FUNCTION complete_studio_module(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION complete_studio_module(bigint) TO authenticated;
