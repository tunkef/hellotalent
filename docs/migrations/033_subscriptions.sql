-- ── 1. SUBSCRIPTIONS TABLE ─────────────────────────────────────
-- One row per subscription period. Renewal = new row.
-- Churn = status expired/cancelled. Re-acquisition = new active row.

CREATE TABLE IF NOT EXISTS subscriptions (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  user_type text NOT NULL CHECK (user_type IN ('candidate', 'employer')),
  plan text NOT NULL CHECK (plan IN ('pro', 'enterprise')),
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'trial', 'expired', 'cancelled')),
  auto_renew boolean NOT NULL DEFAULT true,
  amount integer NOT NULL DEFAULT 0,
  currency text NOT NULL DEFAULT 'TRY',
  started_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT (now() + interval '30 days'),
  renewed_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_subscriptions_user
  ON subscriptions(user_id, user_type);
CREATE INDEX IF NOT EXISTS idx_subscriptions_status
  ON subscriptions(status, expires_at);
CREATE INDEX IF NOT EXISTS idx_subscriptions_type_status
  ON subscriptions(user_type, status);

-- Updated_at trigger
CREATE OR REPLACE FUNCTION update_subscriptions_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER subscriptions_updated_at
  BEFORE UPDATE ON subscriptions
  FOR EACH ROW EXECUTE FUNCTION update_subscriptions_updated_at();


