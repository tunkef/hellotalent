CREATE POLICY subscriptions_user_read ON subscriptions
  FOR SELECT USING (user_id = auth.uid());

-- Admin full access
CREATE POLICY subscriptions_admin_all ON subscriptions
  FOR ALL USING (is_admin());


-- ── 3. EMPLOYER DAILY USAGE TRACKING ───────────────────────────
-- Tracks candidate profile views per day for free tier rate-limiting.
-- Pro/Enterprise skip this check.

CREATE TABLE IF NOT EXISTS employer_daily_usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  usage_date date NOT NULL DEFAULT CURRENT_DATE,
  candidate_views integer NOT NULL DEFAULT 0,
  messages_sent integer NOT NULL DEFAULT 0,
  UNIQUE(user_id, usage_date)
);

CREATE INDEX IF NOT EXISTS idx_employer_daily_usage_user_date
  ON employer_daily_usage(user_id, usage_date);

ALTER TABLE employer_daily_usage ENABLE ROW LEVEL SECURITY;

CREATE POLICY edu_user_read ON employer_daily_usage
  FOR SELECT USING (user_id = auth.uid());

CREATE POLICY edu_admin_all ON employer_daily_usage
  FOR ALL USING (is_admin());


-- ── 4. HELPER: is_premium_employer() ───────────────────────────
-- Returns true if the current user has an active pro/enterprise subscription.

CREATE OR REPLACE FUNCTION is_premium_employer()
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM subscriptions
    WHERE user_id = auth.uid()
      AND user_type = 'employer'
      AND plan IN ('pro', 'enterprise')
      AND status IN ('active', 'trial')
      AND expires_at > now()
  );
END;
$$;


-- ── 5. HELPER: get_employer_plan() ─────────────────────────────
-- Returns the current plan name for the employer, or 'demo' if none.

CREATE OR REPLACE FUNCTION get_employer_plan()
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_plan text;
BEGIN
  SELECT plan INTO v_plan
  FROM subscriptions
  WHERE user_id = auth.uid()
    AND user_type = 'employer'
    AND status IN ('active', 'trial')
    AND expires_at > now()
  ORDER BY
    CASE plan WHEN 'enterprise' THEN 1 WHEN 'pro' THEN 2 ELSE 3 END
  LIMIT 1;

  RETURN COALESCE(v_plan, 'demo');
END;
$$;


-- ── 6. HELPER: check_employer_usage_limit() ────────────────────
-- Returns true if the employer can still perform the action today.
-- Pro/Enterprise always return true. Demo has limits.
-- action: 'candidate_view' (limit 5/day) or 'message' (limit 0 for demo)

CREATE OR REPLACE FUNCTION check_employer_usage_limit(p_action text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_plan text;
  v_usage record;
BEGIN
  -- Only employers have usage limits
  IF NOT is_employer() THEN RETURN true; END IF;

  v_plan := get_employer_plan();

  -- Pro and Enterprise have no limits
  IF v_plan IN ('pro', 'enterprise') THEN
    RETURN true;
  END IF;

  -- Demo limits
  SELECT candidate_views, messages_sent INTO v_usage
  FROM employer_daily_usage
  WHERE user_id = auth.uid() AND usage_date = CURRENT_DATE;

  IF p_action = 'candidate_view' THEN
    RETURN COALESCE(v_usage.candidate_views, 0) < 5;
  ELSIF p_action = 'message' THEN
    -- Demo users cannot send messages
    RETURN false;
  END IF;

  RETURN true;
END;
$$;


-- ── 7. HELPER: increment_employer_usage() ──────────────────────
-- Increments the daily usage counter. Called after a successful action.

CREATE OR REPLACE FUNCTION increment_employer_usage(p_action text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT is_employer() THEN RETURN; END IF;

  INSERT INTO employer_daily_usage (user_id, usage_date, candidate_views, messages_sent)
  VALUES (
    auth.uid(),
    CURRENT_DATE,
    CASE WHEN p_action = 'candidate_view' THEN 1 ELSE 0 END,
    CASE WHEN p_action = 'message' THEN 1 ELSE 0 END
  )
  ON CONFLICT (user_id, usage_date)
  DO UPDATE SET
    candidate_views = employer_daily_usage.candidate_views +
      CASE WHEN p_action = 'candidate_view' THEN 1 ELSE 0 END,
    messages_sent = employer_daily_usage.messages_sent +
      CASE WHEN p_action = 'message' THEN 1 ELSE 0 END;
END;
$$;

GRANT EXECUTE ON FUNCTION is_premium_employer TO authenticated;
GRANT EXECUTE ON FUNCTION get_employer_plan TO authenticated;
GRANT EXECUTE ON FUNCTION check_employer_usage_limit TO authenticated;
GRANT EXECUTE ON FUNCTION increment_employer_usage TO authenticated;


