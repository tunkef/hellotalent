-- Reuse standard updated_at trigger function if it exists, else create
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_coach_posts_updated_at ON coach_posts;
CREATE TRIGGER trg_coach_posts_updated_at
  BEFORE UPDATE ON coach_posts
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();


