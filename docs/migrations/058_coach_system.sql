-- ── 4a. accept_coach_invite ─────────────────────────────────────────────

CREATE OR REPLACE FUNCTION accept_coach_invite(p_token uuid)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id uuid;
  v_user_email text;
  v_invite coach_invites%ROWTYPE;
  v_profile coach_profiles%ROWTYPE;
BEGIN
  -- Derive authenticated user
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Oturum acilmamis.';
  END IF;

  -- Get user email from auth.users
  SELECT email INTO v_user_email FROM auth.users WHERE id = v_user_id;
  IF v_user_email IS NULL THEN
    RAISE EXCEPTION 'Kullanici e-postasi bulunamadi.';
  END IF;

  -- Check if already a coach
  IF EXISTS (SELECT 1 FROM coach_profiles WHERE id = v_user_id) THEN
    SELECT * INTO v_profile FROM coach_profiles WHERE id = v_user_id;
    RETURN row_to_json(v_profile);
  END IF;

  -- Find and validate invite
  SELECT * INTO v_invite FROM coach_invites WHERE token = p_token;
  IF v_invite.id IS NULL THEN
    RAISE EXCEPTION 'Gecersiz davet baglantisi.';
  END IF;

  IF v_invite.status <> 'pending' THEN
    RAISE EXCEPTION 'Bu davet artik gecerli degil (durum: %).', v_invite.status;
  END IF;

  IF v_invite.expires_at < now() THEN
    -- Auto-expire
    UPDATE coach_invites SET status = 'expired' WHERE id = v_invite.id;
    RAISE EXCEPTION 'Davet suresi dolmus.';
  END IF;

  -- SECURITY: Email must match invite
  IF lower(trim(v_user_email)) <> lower(trim(v_invite.email)) THEN
    RAISE EXCEPTION 'Bu davet farkli bir e-posta adresine gonderilmis. Lutfen dogru hesapla giris yapin.';
  END IF;

  -- Create coach profile
  INSERT INTO coach_profiles (id, invite_id, display_name)
  VALUES (v_user_id, v_invite.id, COALESCE(v_invite.display_name, split_part(v_user_email, '@', 1)))
  RETURNING * INTO v_profile;

  -- Mark invite accepted
  UPDATE coach_invites
  SET status = 'accepted', accepted_at = now()
  WHERE id = v_invite.id;

  RETURN row_to_json(v_profile);
END;
$$;

REVOKE EXECUTE ON FUNCTION accept_coach_invite(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION accept_coach_invite(uuid) TO authenticated;


-- ── 4b. toggle_coach_post_like ──────────────────────────────────────────

CREATE OR REPLACE FUNCTION toggle_coach_post_like(p_post_id bigint)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_candidate_id bigint;
  v_exists boolean;
  v_new_count integer;
BEGIN
  -- Derive candidate
  SELECT id INTO v_candidate_id FROM candidates WHERE user_id = auth.uid();
  IF v_candidate_id IS NULL THEN
    RAISE EXCEPTION 'Aday profili bulunamadi.';
  END IF;

  -- Verify post is published
  IF NOT EXISTS (SELECT 1 FROM coach_posts WHERE id = p_post_id AND status = 'published') THEN
    RAISE EXCEPTION 'Yazi bulunamadi.';
  END IF;

  -- Check existing like
  SELECT EXISTS (
    SELECT 1 FROM coach_post_likes
    WHERE candidate_id = v_candidate_id AND post_id = p_post_id
  ) INTO v_exists;

  IF v_exists THEN
    -- Remove like
    DELETE FROM coach_post_likes
    WHERE candidate_id = v_candidate_id AND post_id = p_post_id;

    UPDATE coach_posts SET like_count = GREATEST(like_count - 1, 0)
    WHERE id = p_post_id
    RETURNING like_count INTO v_new_count;
  ELSE
    -- Add like
    INSERT INTO coach_post_likes (candidate_id, post_id)
    VALUES (v_candidate_id, p_post_id);

    UPDATE coach_posts SET like_count = like_count + 1
    WHERE id = p_post_id
    RETURNING like_count INTO v_new_count;
  END IF;

  RETURN v_new_count;
END;
$$;

REVOKE EXECUTE ON FUNCTION toggle_coach_post_like(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION toggle_coach_post_like(bigint) TO authenticated;


-- ── 4c. enqueue_coach_invite_email (trigger function) ───────────────────
-- Enqueues invite email into existing email_outbox pipeline on coach_invites INSERT

CREATE OR REPLACE FUNCTION enqueue_coach_invite_email()
RETURNS trigger AS $$
BEGIN
  IF NEW.status = 'pending' THEN
    INSERT INTO email_outbox (
      email_type,
      recipient_email,
      template_data,
      dedupe_key
    ) VALUES (
      'coach_invite',
      NEW.email,
      jsonb_build_object(
        'display_name', COALESCE(NEW.display_name, split_part(NEW.email, '@', 1)),
        'invite_url', 'https://hellotalent.ai/coach-studio.html?token=' || NEW.token::text,
        'expires_at', NEW.expires_at::text
      ),
      'coach_invite:' || NEW.id::text
    );
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_coach_invite_email ON coach_invites;
CREATE TRIGGER trg_coach_invite_email
  AFTER INSERT ON coach_invites
  FOR EACH ROW EXECUTE FUNCTION enqueue_coach_invite_email();


