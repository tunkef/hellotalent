-- ── 1a. coach_invites ────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS coach_invites (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email           text NOT NULL,
  display_name    text,
  invited_by      uuid NOT NULL REFERENCES admin_users(id),
  status          text NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending','accepted','expired','revoked')),
  token           uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at      timestamptz NOT NULL DEFAULT now(),
  expires_at      timestamptz NOT NULL DEFAULT (now() + interval '30 days'),
  accepted_at     timestamptz,
  revoked_at      timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_coach_invites_token
  ON coach_invites(token);

CREATE INDEX IF NOT EXISTS idx_coach_invites_email
  ON coach_invites(email);

-- Prevent duplicate pending invitations for same email
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_indexes
    WHERE tablename = 'coach_invites'
      AND indexname = 'idx_coach_invites_pending_unique'
  ) THEN
    CREATE UNIQUE INDEX idx_coach_invites_pending_unique
      ON coach_invites(email)
      WHERE status = 'pending';
  END IF;
END
$$;


-- ── 1b. coach_profiles ──────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS coach_profiles (
  id              uuid PRIMARY KEY REFERENCES auth.users(id),
  invite_id       bigint NOT NULL REFERENCES coach_invites(id),
  display_name    text NOT NULL,
  title           text,
  avatar_url      text,
  is_active       boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL DEFAULT now()
);


-- ── 1c. coach_posts ─────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS coach_posts (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coach_id        uuid NOT NULL REFERENCES coach_profiles(id),
  title           text NOT NULL,
  excerpt         text,
  body            text NOT NULL,
  category        text NOT NULL
                    CHECK (category IN ('mulakat_ipucu','yetkinlik_rehberi','kariyer_hikaye','sektor_analiz')),
  related_role    text,
  related_competency_code text,
  status          text NOT NULL DEFAULT 'draft'
                    CHECK (status IN ('draft','submitted','changes_requested','published','archived','rejected')),
  admin_note      text,
  like_count      integer NOT NULL DEFAULT 0,
  published_at    timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_coach_posts_feed
  ON coach_posts(status, published_at DESC)
  WHERE status = 'published';

CREATE INDEX IF NOT EXISTS idx_coach_posts_coach
  ON coach_posts(coach_id);

CREATE INDEX IF NOT EXISTS idx_coach_posts_status
  ON coach_posts(status);


-- ── 1d. coach_post_likes ────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS coach_post_likes (
  candidate_id    bigint NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  post_id         bigint NOT NULL REFERENCES coach_posts(id) ON DELETE CASCADE,
  created_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (candidate_id, post_id)
);


