  FOR ALL USING (is_admin());

-- Coaches can read their own invite (for studio acceptance check)
CREATE POLICY coach_invites_own_read ON coach_invites
  FOR SELECT USING (
    email = (SELECT email FROM auth.users WHERE id = auth.uid())
  );


-- ── 3b. coach_profiles ─────────────────────────────────────────────────

ALTER TABLE coach_profiles ENABLE ROW LEVEL SECURITY;

-- Coach reads own
CREATE POLICY coach_profiles_own_read ON coach_profiles
  FOR SELECT USING (id = auth.uid());

-- Coach updates own (display_name, title, avatar_url)
CREATE POLICY coach_profiles_own_update ON coach_profiles
  FOR UPDATE USING (id = auth.uid())
  WITH CHECK (id = auth.uid());

-- Admin full CRUD
CREATE POLICY coach_profiles_admin ON coach_profiles
  FOR ALL USING (is_admin());

-- Authenticated users can read active coach profiles (for feed display)
CREATE POLICY coach_profiles_authenticated_read ON coach_profiles
  FOR SELECT USING (
    is_active = true
    AND auth.uid() IS NOT NULL
  );


-- ── 3c. coach_posts ────────────────────────────────────────────────────

ALTER TABLE coach_posts ENABLE ROW LEVEL SECURITY;

-- Coach reads own posts (any status)
CREATE POLICY coach_posts_coach_read ON coach_posts
  FOR SELECT USING (
    coach_id = auth.uid()
  );

-- Coach inserts own posts
CREATE POLICY coach_posts_coach_insert ON coach_posts
  FOR INSERT WITH CHECK (
    coach_id = auth.uid()
    AND EXISTS (SELECT 1 FROM coach_profiles WHERE id = auth.uid() AND is_active = true)
  );

-- Coach updates own draft/changes_requested posts
CREATE POLICY coach_posts_coach_update ON coach_posts
  FOR UPDATE USING (
    coach_id = auth.uid()
    AND status IN ('draft', 'changes_requested')
  ) WITH CHECK (
    coach_id = auth.uid()
  );

-- Admin full CRUD
CREATE POLICY coach_posts_admin ON coach_posts
  FOR ALL USING (is_admin());

-- Authenticated candidates can read published posts from active coaches
CREATE POLICY coach_posts_published_read ON coach_posts
  FOR SELECT USING (
    status = 'published'
    AND auth.uid() IS NOT NULL
    AND EXISTS (SELECT 1 FROM coach_profiles cp WHERE cp.id = coach_posts.coach_id AND cp.is_active = true)
  );


-- ── 3d. coach_post_likes ───────────────────────────────────────────────

ALTER TABLE coach_post_likes ENABLE ROW LEVEL SECURITY;

-- Candidate reads own likes
CREATE POLICY coach_post_likes_own_read ON coach_post_likes
  FOR SELECT USING (candidate_id = get_my_candidate_id());

-- Candidate inserts own like
CREATE POLICY coach_post_likes_own_insert ON coach_post_likes
  FOR INSERT WITH CHECK (candidate_id = get_my_candidate_id());

-- Candidate deletes own like
CREATE POLICY coach_post_likes_own_delete ON coach_post_likes
  FOR DELETE USING (candidate_id = get_my_candidate_id());

-- Admin can read all (analytics)
CREATE POLICY coach_post_likes_admin ON coach_post_likes
  FOR ALL USING (is_admin());


