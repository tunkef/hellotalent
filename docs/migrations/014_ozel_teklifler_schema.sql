-- approved → active (payment captured at approve time, visibility delayed by start_date)
CREATE OR REPLACE FUNCTION activate_due_campaigns()
RETURNS void AS $$
BEGIN
  UPDATE campaigns
  SET status = 'active', published_at = now()
  WHERE status = 'approved'
    AND payment_status = 'captured'
    AND (start_date IS NULL OR start_date <= now());
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- active → ended (end_date passed)
CREATE OR REPLACE FUNCTION end_expired_campaigns()
RETURNS void AS $$
BEGIN
  UPDATE campaigns
  SET status = 'ended', ended_at = now()
  WHERE status = 'active'
    AND end_date <= now();
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- ended → archived (7 days after ending)
CREATE OR REPLACE FUNCTION archive_old_ended_campaigns()
RETURNS void AS $$
BEGIN
  UPDATE campaigns
  SET status = 'archived', archived_at = now()
  WHERE status = 'ended'
    AND ended_at < now() - interval '7 days';
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

